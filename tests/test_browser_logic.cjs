const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('index.html','utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(script, 'inline script exists');
const source = script[1].replace(/\binit\(\);\s*$/, '');
new vm.Script(source, {filename:'index.html'});
const values = {model:'prius',years:'5',distance:'10000',used:'3',purchaseRegion:'東京都',eligibilityMode:'inclusive',deliveryFee:'0',phevElectricShare:'0.5',electricYen:'30',phevKwhPer100km:'16',chargeEfficiency:'0.9',chargerInstallMan:'10',grant:'0',purchaseFeesNew:'10',purchaseFeesUsed:'0',annualTaxMan:'3',inspectionMan:'0'};
const elements = new Map(Object.entries(values).map(([k,v])=>[k,{value:v,innerHTML:'',textContent:''}]));
for(const id of ['results','chart','regression','audit','regionWarnings']) elements.set(id,{innerHTML:'',textContent:''});
const context={document:{getElementById:id=>{assert.ok(elements.has(id),'missing control: '+id);return elements.get(id);}},console,Math,Number,Array,Date};
vm.createContext(context);
vm.runInContext(source,context);
vm.runInContext("catalog={vehicles:[{id:'prius',powertrains:[{id:'phev',label:'PHEV',grade:'Z',newPriceMan:400,kmPerLiter:20,priceEvidence:{kind:'assumption'}}]}]};assumptions={usedPriceRatios:{3:0.8},fuelYenPerLiter:175,annualMaintenanceMan:{phev:5},annualVoluntaryInsuranceMan:{phev:3},annualCompulsoryInsuranceMan:{phev:1},grantMan:0,resaleEvidence:{kind:'assumption'}};usedListings=[];",context);
const calc=()=>vm.runInContext("calculate(catalog.vehicles[0].powertrains[0],false)",context);
let x=calc();
assert.ok(Math.abs(x.fuelCost-21.875)<1e-8);
assert.ok(Math.abs(x.electricCost-(5*10000*.5*16/100*30/.9/10000))<1e-8);
assert.equal(x.chargerInstall,10);
assert.equal(x.purchaseFees,10);
assert.equal(x.annualTaxCost,15);
assert.equal(x.insuranceCost,20);
assert.equal(x.voluntaryInsuranceCost,15);
assert.equal(x.compulsoryInsuranceCost,5);
assert.equal(x.maintenanceCost,25);
assert.ok(Math.abs(x.running-(x.fuelCost+x.electricCost+x.maintenanceCost+x.insuranceCost+x.annualTaxCost+x.inspectionCost))<1e-8);
assert.equal(x.inspectionCost,0);
assert.equal(x.inspectionCount,2);
assert.equal(vm.runInContext('inspectionCountForOwnership(3,5)',context),3);
assert.equal(vm.runInContext('inspectionCountForOwnership(0,3)',context),1);
assert.equal(vm.runInContext('inspectionCountForOwnership(0,5)',context),2);
assert.equal(vm.runInContext("annualTaxEstimateMan('prius',{id:'phev'}).man",context),3.6);
elements.get('annualTaxMan').value='auto';
assert.equal(calc().annualTaxCost,18);
elements.get('annualTaxMan').value='3';
assert.ok(Math.abs(x.cost-(x.price+x.purchaseFees+x.running+x.chargerInstall-x.resale))<1e-8);
elements.get('inspectionMan').value='5';
const withInspection=calc();
assert.ok(withInspection.inspectionCost>0);
assert.equal(withInspection.cost-x.cost,withInspection.inspectionCost);
elements.get('inspectionMan').value='0';
elements.get('chargeEfficiency').value='1';
const efficient=calc();
assert.ok(efficient.electricCost<x.electricCost);
elements.get('phevElectricShare').value='0';
const gasOnly=calc();
assert.equal(gasOnly.electricCost,0);
assert.ok(gasOnly.fuelCost>x.fuelCost);
elements.get('phevElectricShare').value='0.5';
elements.get('chargeEfficiency').value='0.9';
vm.runInContext("usedListings=[{vehicleId:'prius',powertrain:'phev',grade:'Z',modelYear:2023,km:30000,totalMan:350,repairHistory:'none',drive:'2WD',seats:5,verifiedAt:'2026-10-31',purchaseEligibility:'restricted',salesRegion:'茨城県内限定'}];",context);
assert.equal(vm.runInContext("matchingListings(catalog.vehicles[0].powertrains[0]).length",context),0);
elements.get('purchaseRegion').value='茨城県';
assert.equal(vm.runInContext("matchingListings(catalog.vehicles[0].powertrains[0]).length",context),1);
elements.get('eligibilityMode').value='strict';
elements.get('purchaseRegion').value='東京都';
assert.equal(vm.runInContext("matchingListings(catalog.vehicles[0].powertrains[0]).length",context),0);
vm.runInContext("render()",context);
assert.match(elements.get('results').innerHTML,/燃費・維持費の根拠/);
assert.match(elements.get('results').innerHTML,/充電設備/);
assert.match(elements.get('results').innerHTML,/任意保険/);
assert.match(elements.get('results').innerHTML,/自賠責保険/);
assert.match(elements.get('results').innerHTML,/整備・消耗品/);
console.log('PASS: JS syntax, PHEV TCO, charging efficiency, region filtering, rendered evidence');
